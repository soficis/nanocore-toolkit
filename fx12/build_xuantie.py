#!/usr/bin/env python3
"""Build freestanding NanoCore FX with the Xuantie toolchain natively in WSL.

Docker-free equivalent of tools/custom_fx/build.py: identical FLAGS list, identical
linker-script template, identical compile/link/objcopy/objdump/readelf/nm step order and
artifact set. The only change is the process invocation: `wsl -e bash <script>` running
~/nanocore_tools/xuantie/Xuantie-900-gcc-elf-newlib-x86_64-V2.6.1/bin/riscv64-unknown-elf-*
instead of `docker run --rm debian:bookworm-slim`.

No device operations. Output is written only under --output.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess

REPO = Path(os.environ.get(
    'NANOCORE_REPO', Path.home() / 'nanocore_tools' / 'repos' / 're-nanocore')).expanduser()

# Verbatim from tools/custom_fx/build.py:14-17.
FLAGS = ['-march=rv32imafdcpzpsfoperand_xtheade', '-mabi=ilp32d',
         '-Os', '-std=c11', '-ffreestanding', '-fno-builtin',
         '-ffunction-sections', '-fdata-sections', '-msmall-data-limit=0',
         '-mno-relax', '-ffp-contract=off', '-Wall', '-Wextra', '-Werror']
# Verbatim from tools/custom_fx/build.py:18.
SITES = {'1.10': 0x400720ae, '1.11': 0x400747ee, '1.12': 0x40074e5e}
ENTRIES = {'gain': 'nc_fx_velvet_gain', 'univibe': 'nc_fx_univibe',
           'chorus': 'nc_fx_chorus'}
LIMITS = {'gain': 1392, 'univibe': 1298, 'chorus': 0x10000}

XUANTIE_HOME = '$HOME/nanocore_tools/xuantie'
DEFAULT_TOOL = (XUANTIE_HOME +
                '/Xuantie-900-gcc-elf-newlib-x86_64-V2.6.1/bin/riscv64-unknown-elf-')


def wsl_path(p):
    """Windows absolute path -> /mnt/<drive>/... path visible to WSL."""
    p = Path(p).resolve()
    drive = p.drive.rstrip(':').lower()
    rest = str(p)[len(p.drive):].replace('\\', '/')
    return '/mnt/' + drive + rest


def q(s):
    return "'" + s.replace("'", "'\\''") + "'"


def linker_script(address, entry, limit):
    # Verbatim template from tools/custom_fx/build.py:41-52.
    return f'''ENTRY({entry})
SECTIONS {{
 . = 0x{address:x};
 .payload 0x{address:x} : SUBALIGN(2) {{ *(.text.{entry}) *(.text*) . = ALIGN(4); *(.rodata*) *(.srodata*) }}
 .forbidden : {{ *(.data*) *(.sdata*) *(.bss*) *(.sbss*) *(COMMON) }}
 /DISCARD/ : {{ *(.comment) *(.note*) *(.eh_frame*) }}
 ASSERT(ADDR(.payload) == 0x{address:x}, "entry address moved")
 ASSERT({entry} == 0x{address:x}, "entry is not first")
 ASSERT(SIZEOF(.payload) <= {limit}, "replacement exceeds native routine")
 ASSERT(SIZEOF(.forbidden) == 0, "persistent globals prohibited")
}}
'''


def bash_array(name, values):
    return name + '=(' + ' '.join(q(v) for v in values) + ')\n'


def build(out, effect, address, entry, limit, tool, force=False):
    out = Path(out).resolve()
    out.mkdir(parents=True, exist_ok=force)
    src = REPO / 'firmware/custom-fx/src' / f'{effect}.c'
    inc = REPO / 'firmware/custom-fx/include'
    if not src.is_file():
        raise SystemExit(f'missing source {src}')

    (out / f'{effect}.ld').write_text(linker_script(address, entry, limit))
    wout, wsrc, winc = wsl_path(out), wsl_path(src), wsl_path(inc)
    # "$HOME" is expanded by bash in WSL; an explicit --tool-prefix is literal.
    tool_line = ('TOOL="' + tool + '"') if tool.startswith('$HOME') else ('TOOL=' + q(tool))

    lines = ['#!/bin/bash',
             '# generated by build_xuantie.py -- exact analogue of tools/custom_fx/build.py',
             'set -u',
             'cd /',                       # docker's default WORKDIR in the reference
             'mkdir -p /tmp/nc_home',
             tool_line,
             'OUT=' + q(wout),
             bash_array('FLAGS', FLAGS).rstrip('\n'),
             # clean env like a bare container; PATH/HOME only
             'run(){ env -i PATH=/usr/local/bin:/usr/bin:/bin HOME=/tmp/nc_home "$@"; }',
             ]
    lines += [
        f'run "${{TOOL}}gcc" --version > "$OUT/gcc_version.txt" 2>&1',
        f'run "${{TOOL}}ld" --version > "$OUT/ld_version.txt" 2>&1',
        '',
        '# 1. compile (build.py:55-56)',
        f'run "${{TOOL}}gcc" "${{FLAGS[@]}}" {q("-I" + winc)} -c {q(wsrc)}'
        f' -o "$OUT/{effect}.o" > "$OUT/01_compile.log" 2>&1',
        'if [ $? -ne 0 ]; then echo "COMPILE FAILED"; cat "$OUT/01_compile.log"; exit 1; fi',
        '# 2. link (build.py:57-59)',
        f'run "${{TOOL}}gcc" "${{FLAGS[@]}}" -nostdlib -nostartfiles'
        f' -Wl,-T,"$OUT/{effect}.ld",-Map,"$OUT/{effect}.map",--no-relax'
        f' "$OUT/{effect}.o" -o "$OUT/{effect}.elf" > "$OUT/02_link.log" 2>&1',
        'if [ $? -ne 0 ]; then echo "LINK FAILED"; cat "$OUT/02_link.log"; exit 1; fi',
        '# 3. undefined-symbol gate (build.py:60-62)',
        f'run "${{TOOL}}nm" -u "$OUT/{effect}.elf" > "$OUT/03_nm_u.txt" 2>&1',
        'if [ $? -ne 0 ]; then echo "NM FAILED"; cat "$OUT/03_nm_u.txt"; exit 1; fi',
        '# 4. objcopy -O binary --only-section=.payload (build.py:63-64)',
        f'run "${{TOOL}}objcopy" -O binary --only-section=.payload'
        f' "$OUT/{effect}.elf" "$OUT/{effect}.bin" > "$OUT/04_objcopy.log" 2>&1',
        'if [ $? -ne 0 ]; then echo "OBJCOPY FAILED"; cat "$OUT/04_objcopy.log"; exit 1; fi',
        '# 5. objdump -d (build.py:65-66)',
        f'run "${{TOOL}}objdump" -d "$OUT/{effect}.elf" > "$OUT/{effect}.asm" 2>&1',
        '# 6. readelf -h -A -r (build.py:67-68)',
        f'run "${{TOOL}}readelf" -h -A -r "$OUT/{effect}.elf" > "$OUT/{effect}.attributes.txt" 2>&1',
        'echo "== done"',
        f'ls -l "$OUT/{effect}.bin"',
        '']
    script = out / 'run_wsl.sh'
    # LF only: bash rejects CRLF (the .ld keeps build.py's own write semantics).
    with open(script, 'w', newline='\n') as fh:
        fh.write('\n'.join(lines))

    invocation = f'wsl -e bash "{wsl_path(script)}"'
    print('== ' + invocation)
    proc = subprocess.run(['wsl', '-e', 'bash', wsl_path(script)],
                          text=True, capture_output=True)
    if proc.returncode != 0:
        print(proc.stdout)
        print(proc.stderr)
        raise SystemExit(f'WSL build failed (exit {proc.returncode})')

    undefined = (out / '03_nm_u.txt').read_text(errors='replace').strip()
    if undefined:
        raise SystemExit('Unresolved symbols: ' + undefined)

    data = (out / f'{effect}.bin').read_bytes()
    receipt = {
        'firmware_version': None,
        'flags': FLAGS,
        'compiler': (out / 'gcc_version.txt').read_text().splitlines()[0],
        'binutils': (out / 'ld_version.txt').read_text().splitlines()[0],
        'toolchain_prefix': tool,
        'container_replacement': 'WSL native (no Docker)',
        'wsl_invocation': invocation,
        'linker_script_sha256': hashlib.sha256((out / f'{effect}.ld').read_bytes()).hexdigest(),
        'header_sha256': hashlib.sha256(
            (REPO / 'firmware/custom-fx/include/nc_fx.h').read_bytes()).hexdigest(),
        'artifacts': {effect: {
            'address': hex(address), 'size': len(data),
            'sha256': hashlib.sha256(data).hexdigest(),
            'source_sha256': hashlib.sha256(src.read_bytes()).hexdigest(),
            'entry': entry, 'unresolved_symbols': [],
            'injection_candidate': effect in ('gain', 'univibe'),
            'capacity': limit}},
    }
    return receipt


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--output', required=True)
    p.add_argument('--version', choices=sorted(SITES), default='1.12',
                   help='firmware version, selects the injection address')
    p.add_argument('--address', help='override the injection address (0x...)')
    p.add_argument('--entry', help='override the entry symbol')
    p.add_argument('--limit', type=lambda s: int(s, 0),
                   help='override the capacity limit in bytes')
    p.add_argument('--effect', choices=sorted(ENTRIES), default='univibe')
    p.add_argument('--tool-prefix', default=DEFAULT_TOOL,
                   help='WSL path prefix ending in riscv64-unknown-elf-')
    p.add_argument('--force', action='store_true', help='allow an existing output dir')
    a = p.parse_args()

    address = int(a.address, 16) if a.address else SITES[a.version]
    entry = a.entry or ENTRIES[a.effect]
    limit = a.limit if a.limit is not None else LIMITS[a.effect]
    receipt = build(a.output, a.effect, address, entry, limit,
                    a.tool_prefix, a.force)
    receipt['firmware_version'] = a.version
    out = Path(a.output).resolve()
    (out / 'build.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print(json.dumps(receipt, indent=2))


if __name__ == '__main__':
    main()
